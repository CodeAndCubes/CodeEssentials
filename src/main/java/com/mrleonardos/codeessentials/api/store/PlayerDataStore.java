package com.mrleonardos.codeessentials.api.store;

import java.util.Map;
import java.util.UUID;

import com.mrleonardos.codeessentials.api.model.PlayerRecord;

/**
 * Хранилище состояния игроков: точка расширения для чужих провайдеров.
 *
 * <p>
 * Встроенный провайдер {@code json} держит два файла в папке мира: дома со стеком возврата и
 * кулдауны. Чужой мод регистрирует свою реализацию в {@code EssentialsApi}, а выбирается она по
 * имени из настройки {@code storage.playerProvider}. Файлы настроек, варпы и спавн через SPI не
 * ходят: их правит человек, и json там остаётся всегда.
 *
 * <p>
 * Сбой провайдера не роняет сервер: мод продолжает работать на последнем удачном снимке, причина
 * попадает в лог.
 */
public interface PlayerDataStore {

    /** Ключ срока между tpa-запросами в карте кулдаунов, остальные ключи это причины переноса. */
    String REQUEST_COOLDOWN_KEY = "request";

    /** Имя провайдера, по нему его выбирает настройка {@code storage.playerProvider}. */
    String id();

    /** Прочитать игроков целиком. Вызывается на старте сервера. */
    Map<UUID, PlayerRecord> loadPlayers();

    /**
     * Прочитать кулдауны целиком: игрок, ключ причины, абсолютная метка в epoch millis.
     *
     * <p>
     * Протухшие записи разрешено отдавать как есть, мод отбрасывает их сам при загрузке.
     */
    Map<UUID, Map<String, Long>> loadCooldowns();

    /**
     * Применить пачку правок. Частичного применения нет: провайдер либо записывает всё, либо
     * отвечает отказом и оставляет хранилище в прежнем состоянии.
     *
     * <p>
     * Хранилищу принадлежат три кода отказа: {@code PROVIDER_FAILED}, когда носитель не смог
     * записать, {@code UNSUPPORTED}, когда правка ему не по силам (так отвечает провайдер, который
     * ведёт дома, но не ведёт кулдауны), и {@code TIMEOUT}, когда запись не уложилась в свой срок.
     * Остальные значения {@link StoreResult.Failure} проверяет модель до обращения к хранилищу.
     */
    StoreResult apply(ChangeBatch batch);
}
