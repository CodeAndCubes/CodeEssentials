package com.mrleonardos.codeessentials.api.teleport;

import com.mrleonardos.codeessentials.api.model.Point;

/**
 * Как искать место для приземления: точка расширения для чужих правил.
 *
 * <p>
 * Встроенная политика {@code builtin} проверяет точную точку, затем поднимается, опускается и
 * обходит кольца по горизонтали. Мод с воздушными островами, кастомными жидкостями или своими
 * опасными блоками регистрирует свою политику в {@code EssentialsApi} и получает весь поиск себе.
 *
 * <p>
 * Политика обязана держать слово, которое дают её ответы: {@code EXACT} только для точки, где игрок
 * и просил оказаться, а найденное место безопасно по правилам {@link BlockView}. Отказ бесплатен и
 * ничего не стоит игроку, поэтому сомнительное место лучше не отдавать.
 */
public interface SafeSpotPolicy {

    /** Имя политики, по нему её выбирает настройка и вытесняет чужая. */
    String id();

    /**
     * Найти место рядом с просьбой.
     *
     * @param view   взгляд на мир того измерения, куда несут игрока
     * @param hint   куда просили
     * @param limits насколько далеко разрешено отойти
     */
    SafeSpotResult find(BlockView view, Point hint, SafeSpotLimits limits);
}
