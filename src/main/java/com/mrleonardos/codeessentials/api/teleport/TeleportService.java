package com.mrleonardos.codeessentials.api.teleport;

import java.util.List;
import java.util.Optional;
import java.util.UUID;

import com.mrleonardos.codeessentials.api.store.StoreResult;

/**
 * Движок переносов: единственная дорога, по которой мод двигает игрока.
 *
 * <p>
 * На игрока приходится не больше одной активной работы плюс один слот на следующую. Выигрывает
 * последняя просьба: работа в задержке уступает место сразу, работа в переносе доигрывает, а
 * ожидающая в слоте отдаёт его новой. Очереди нет, потому что отложенный перенос через минуту
 * пугает игрока сильнее, чем понятный отказ.
 *
 * <p>
 * Просьбы подаются в главном потоке. Из чужого потока это делают через планировщик ядра, иначе
 * правка снимка разъедется с тиком сервера.
 */
public interface TeleportService {

    /**
     * Подать просьбу. Возвращённая работа это снимок на момент подачи: она уже может быть отменена,
     * если слушатель не пустил перенос.
     */
    TeleportJob request(TeleportRequest request);

    /** Активная работа игрока или пустой ответ. */
    Optional<TeleportJob> job(UUID player);

    /** Все активные работы, для {@code /essentials jobs}. */
    List<TeleportJob> jobs();

    /**
     * Снять активную работу игрока.
     *
     * @return снятая работа или пустой ответ, если снимать было нечего
     */
    Optional<TeleportJob> cancel(UUID player, CancelReason reason);

    /**
     * Сколько миллисекунд ещё ждать до следующего переноса по этой причине.
     *
     * @return ноль, если ждать нечего
     */
    long cooldownRemaining(UUID player, TeleportCause cause);

    /**
     * Снять кулдауны игрока.
     *
     * <p>
     * Отказ {@code NOT_FOUND} значит, что снимать было нечего. Любой другой отказ значит, что
     * хранилище не приняло правку и кулдауны остались на месте: путать эти два ответа нельзя, иначе
     * администратор читает «кулдаунов нет» там, где на самом деле не удалась запись.
     */
    StoreResult clearCooldowns(UUID player);
}
